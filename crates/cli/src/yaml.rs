//! Write the override as YAML so it can carry Compose's `!reset` tag.

use anyhow::Result;
use chronostack_core::compose::RESET_MARKER;
use serde_json::Value as Json;
use serde_norway::Value as Yaml;
use serde_norway::value::{Tag, TaggedValue};

fn convert(v: &Json) -> Result<Yaml> {
    Ok(match v {
        Json::Object(map) if map.len() == 1 && map.contains_key(RESET_MARKER) => {
            Yaml::Tagged(Box::new(TaggedValue {
                tag: Tag::new("reset"),
                value: convert(&map[RESET_MARKER])?,
            }))
        }
        Json::Object(map) => {
            let mut m = serde_norway::Mapping::new();
            for (k, val) in map {
                m.insert(Yaml::String(k.clone()), convert(val)?);
            }
            Yaml::Mapping(m)
        }
        Json::Array(items) => Yaml::Sequence(items.iter().map(convert).collect::<Result<_>>()?),
        other => serde_norway::to_value(other)?,
    })
}

/// Serialize an override document, turning reset markers into `!reset` tags.
pub fn to_compose_yaml(doc: &Json) -> Result<String> {
    Ok(format!(
        "# Generated by ChronoStack — do not edit; recreated by `chronostack up`.\n{}",
        serde_norway::to_string(&convert(doc)?)?
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn emits_reset_tags() {
        let doc = json!({"services": {"web": {
            "ports": { RESET_MARKER: [] },
            "container_name": { RESET_MARKER: null },
            "environment": { "A": "1" }
        }}});
        let y = to_compose_yaml(&doc).unwrap();
        assert!(y.contains("ports: !reset []"), "{y}");
        assert!(y.contains("container_name: !reset null"), "{y}");
        assert!(y.contains("A: '1'") || y.contains("A: \"1\""), "{y}");
    }
}
